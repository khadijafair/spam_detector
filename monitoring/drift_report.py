"""
drift_report.py — Data-drift monitoring with Evidently.

Compares a "current" window of messages against a reference sample of the
training data, on the text itself and on features the model depends on
(message length, URL / money / phone / number / email tokens, SVM score,
predicted-spam flag). No labels are needed, so it can run on production traffic.

Usage (from the project root):
    python -m monitoring.drift_report --demo
        Two reproducible scenarios on the public dataset:
          stable      reference vs. another random sample of the same 5 corpora
          new_source  reference vs. Nazario, a phishing corpus left out of the reference
    python -m monitoring.drift_report --current data/feedback.jsonl
    python -m monitoring.drift_report --current new_messages.csv --text-col text

Writes reports/drift_<name>.html (Evidently report), reports/drift_summary.{md,json}
and logs each scenario to MLflow.
"""
import argparse
import json
import os
from pathlib import Path

import mlflow
import pandas as pd
from evidently import DataDefinition, Dataset, Report
from evidently.presets import DataDriftPreset

import core.config as config
from core import tracking
from core.spam_utils import clean_text_advanced, load_artifacts
from research.evaluate import REPORTS_DIR, SEED, load_master

SAMPLE = 3000
HOLDOUT_SOURCE = "Nazario"
TOKENS = ["urltoken", "moneytoken", "phonetoken", "numbertoken", "emailtoken"]
NUMERIC = ["n_tokens", *[f"{t}_count" for t in TOKENS], "svm_score", "predicted_spam"]


def features(clean_texts: pd.Series) -> pd.DataFrame:
    model, vec = load_artifacts(config.MODEL_PATH, config.VECTORIZER_PATH)
    df = pd.DataFrame({"text": clean_texts.str.slice(0, 3000).values})
    tokens = clean_texts.str.split()
    df["n_tokens"] = tokens.str.len().values
    for t in TOKENS:
        df[f"{t}_count"] = tokens.apply(lambda ws, t=t: ws.count(t)).values
    df["svm_score"] = model.decision_function(vec.transform(clean_texts)).round(4)
    df["predicted_spam"] = (df["svm_score"] > 0).astype(int)
    return df


def run_drift(name: str, reference: pd.DataFrame, current: pd.DataFrame) -> dict:
    definition = DataDefinition(text_columns=["text"], numerical_columns=NUMERIC)
    snapshot = Report([DataDriftPreset()]).run(
        Dataset.from_pandas(current, data_definition=definition),
        Dataset.from_pandas(reference, data_definition=definition))
    REPORTS_DIR.mkdir(exist_ok=True)
    html = REPORTS_DIR / f"drift_{name}.html"
    snapshot.save_html(str(html))

    result = {"reference_messages": len(reference), "current_messages": len(current), "columns": {}}
    for m in snapshot.dict()["metrics"]:
        metric = m["metric_name"]
        if metric.startswith("DriftedColumnsCount"):
            result["drifted_columns"] = int(m["value"]["count"])
            result["drifted_share"] = round(float(m["value"]["share"]), 3)
        elif metric.startswith("ValueDrift"):
            col = metric.split("column=")[1].split(",")[0]
            method = metric.split("method=")[1].split(",")[0]
            result["columns"][col] = {"method": method, "value": round(float(m["value"]), 4)}
    result["dataset_drift"] = result["drifted_share"] >= 0.5
    result["predicted_spam_rate_reference"] = round(float(reference["predicted_spam"].mean()) * 100, 1)
    result["predicted_spam_rate_current"] = round(float(current["predicted_spam"].mean()) * 100, 1)

    with mlflow.start_run(run_name=f"drift_{name}"):
        mlflow.log_params({"scenario": name, "reference_messages": len(reference),
                           "current_messages": len(current)})
        mlflow.log_metrics({"drifted_columns": result["drifted_columns"],
                            "drifted_share": result["drifted_share"],
                            "predicted_spam_rate_current": result["predicted_spam_rate_current"]})
        mlflow.log_artifact(str(html))
    print(f"[{name}] drifted columns: {result['drifted_columns']}/{len(result['columns'])} "
          f"-> dataset drift: {result['dataset_drift']}  ({html})")
    return result


def load_current(path: str, text_col: str) -> pd.Series:
    p = Path(path)
    if p.suffix == ".jsonl":
        texts = [json.loads(line)["text"] for line in p.read_text(encoding="utf-8").splitlines() if line.strip()]
    else:
        texts = pd.read_csv(p)[text_col].dropna().astype(str).tolist()
    if len(texts) < 30:
        raise SystemExit(f"Only {len(texts)} messages in {p}: too few for a meaningful drift test (need >= 30).")
    return pd.Series(texts).apply(clean_text_advanced)


def to_markdown(results: dict) -> str:
    lines = ["# Drift monitoring (generated by `python -m monitoring.drift_report`)", "",
             f"Reference: {SAMPLE:,} emails sampled from the training corpora. Drift is flagged when at least "
             "half of the 9 monitored columns drift (Evidently `DataDriftPreset`: normed Wasserstein distance "
             "on numeric features, Jensen-Shannon on the predicted-spam flag, text-content drift on the text).", "",
             "| Scenario | Current window | Drifted columns | Dataset drift | Predicted spam rate (ref → current) |",
             "|---|---|---|---|---|"]
    for name, r in results.items():
        lines.append(f"| {name} | {r['current_messages']:,} emails | {r['drifted_columns']}/{len(r['columns'])} | "
                     f"{'**yes**' if r['dataset_drift'] else 'no'} | "
                     f"{r['predicted_spam_rate_reference']}% → {r['predicted_spam_rate_current']}% |")
    lines += ["", "Per-column detail is in `drift_summary.json`; the full interactive reports are the "
              "`drift_*.html` files (regenerate them locally, they are not versioned).", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--demo", action="store_true")
    parser.add_argument("--current", help="CSV or feedback .jsonl with the messages to monitor")
    parser.add_argument("--text-col", default="text")
    args = parser.parse_args()
    if not args.demo and not args.current:
        parser.error("use --demo or --current FILE")

    tracking.setup()
    df = load_master()
    results = {}
    if args.demo:
        pool = df[df["source"] != HOLDOUT_SOURCE].sample(frac=1, random_state=SEED)
        reference = features(pool["clean_text"].iloc[:SAMPLE])
        stable = features(pool["clean_text"].iloc[SAMPLE:2 * SAMPLE])
        new_source = features(df[df["source"] == HOLDOUT_SOURCE]["clean_text"])
        results["stable"] = run_drift("stable", reference, stable)
        results["new_source"] = run_drift("new_source", reference, new_source)
    else:
        reference = features(df["clean_text"].sample(n=SAMPLE, random_state=SEED))
        results["current"] = run_drift("current", reference, features(load_current(args.current, args.text_col)))

    (REPORTS_DIR / "drift_summary.json").write_text(json.dumps(results, indent=2))
    (REPORTS_DIR / "drift_summary.md").write_text(to_markdown(results))


if __name__ == "__main__":
    os.environ.setdefault("MLFLOW_DISABLE_AGENT_HINT", "1")
    main()
